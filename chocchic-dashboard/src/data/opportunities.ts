const levelScore = { Low: 1, Medium: 2, High: 3 } as const;

/**
 * Commercial prioritisation score (max 27):
 * Impact×3 + Sales potential×3 + (4 − Difficulty)×2 + (4 − Integration)×1
 */
export function opportunityScore(o: Opportunity) {
  return (
    levelScore[o.impact] * 3 +
    levelScore[o.sales] * 3 +
    (4 - levelScore[o.difficulty]) * 2 +
    (4 - levelScore[o.integrationLevel])
  );
}

export const scoreFormula =
  "Skor = Impact×3 + Satış potansiyeli×3 + (4 − Zorluk)×2 + (4 − Entegrasyon)×1  (Low=1, Medium=2, High=3; maks. 27). Eşitlikte P-önceliği ve ID sırası.";

export function topOpportunities(n = 10) {
  return [...opportunities]
    .sort(
      (a, b) =>
        opportunityScore(b) - opportunityScore(a) ||
        a.priority.localeCompare(b.priority) ||
        a.id.localeCompare(b.id),
    )
    .slice(0, n);
}
